"""
Runs the compiled dbt analyses (one per business question) against the warehouse
and prints the answers. With --markdown, writes them to docs/sample_answers.md.

    cd dbt && dbt compile --select analyses   # (make answers does this for you)
    python scripts/answer_questions.py --markdown
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
COMPILED = ROOT / "dbt/target/compiled/casino_dwh/analyses"
DB = Path(os.environ.get("DUCKDB_PATH", ROOT / "warehouse/casino_dwh.duckdb"))


def to_markdown(cols: list[str], rows: list[tuple]) -> str:
    def fmt(v):
        return "" if v is None else (f"{v:,.2f}" if isinstance(v, float) else str(v))

    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit", type=int, default=10)
    ap.add_argument("--markdown", action="store_true")
    args = ap.parse_args()

    con = duckdb.connect(str(DB), read_only=True)
    md = ["# Sample answers\n", "Generated by `make answers` from the synthetic dataset.\n"]
    for f in sorted(COMPILED.glob("q*.sql")):
        sql = f.read_text()
        title = "\n".join(line[3:] for line in sql.splitlines() if line.startswith("-- Q"))
        res = con.sql(f"select * from ({sql}) limit {args.limit}")
        cols, rows = res.columns, res.fetchall()
        print(f"\n{'=' * 100}\n{title}\n{'=' * 100}")
        res.show()
        md += [f"## {f.stem}\n", "\n".join(f"> {t}  " for t in title.splitlines()), "", to_markdown(cols, rows), ""]

    if args.markdown:
        out = ROOT / "docs/sample_answers.md"
        out.write_text("\n".join(md) + "\n")
        print(f"\nWritten {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
